#!/usr/bin/env python3
"""Extract the PS7 configuration of the working EBAZ4205 design into ps7_base.tcl.

The PS7 settings (DDR, clocks, MIO, ENET0 on EMIO, SD0) must be reused, not
re-derived. Source: the block design JSON of the existing Vivado project.

Usage: python3 extract_ps7.py <path/to/ebaz4205.bd> [out.tcl]
Default source is the EBAZ_extender project on the development machine.
phase1.tcl applies the overrides for the SAdiy Phase 1 on top of this file.
Read-only/derived parameters (PCW_ACT_*, PCW_UIPARAM_ACT_*, PCW_MIO_TREE_*) are dropped; Vivado
recomputes them.
"""
import json
import sys
from pathlib import Path

DEFAULT_BD = ("/media/patrik/Workspaces/HW/Vivado/EBAZ_extender/EBAZ_extender.srcs/"
              "sources_1/bd/ebaz4205/ebaz4205.bd")
SKIP_PREFIX = ("PCW_ACT_", "PCW_UIPARAM_ACT_", "PCW_MIO_TREE_")  # MIO_TREE_* are derived, stored as lists


def main(argv):
    src = Path(argv[0] if argv else DEFAULT_BD)
    out = Path(argv[1]) if len(argv) > 1 else Path(__file__).with_name("ps7_base.tcl")
    ps7 = json.loads(src.read_text())["design"]["components"]["processing_system7_0"]
    params = ps7["parameters"]
    lines = [
        "# GENERATED by extract_ps7.py from the EBAZ_extender block design. Do not edit.",
        f"# Source IP: {ps7['vlnv']}",
        "set ps7_base [dict create \\",
    ]
    n = 0
    for k in sorted(params):
        if not k.startswith("PCW_") or k.startswith(SKIP_PREFIX):
            continue
        v = params[k]["value"]
        lines.append(f"  CONFIG.{k} {{{v}}} \\")
        n += 1
    lines.append("]")
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}: {n} parameters")


if __name__ == "__main__":
    main(sys.argv[1:])
