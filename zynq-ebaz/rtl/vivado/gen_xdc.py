#!/usr/bin/env python3
"""Generate constraints/ebaz4205.xdc from pins.toml (stdlib only, Python 3.11+).

Usage: python3 gen_xdc.py [--check]
  --check   exit 1 if the committed XDC differs from what would be generated

Rules enforced: unique balls, unique (connector, pin), known connector, a
supported IO standard. Inactive signals are written as comments.
"""
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "pins.toml"
OUT = HERE / "constraints" / "ebaz4205.xdc"
CONNECTORS = {"DATA1", "DATA2", "DATA3"}
IOSTD = {"LVCMOS33"}


def render(cfg):
    default_std = cfg.get("defaults", {}).get("iostandard", "LVCMOS33")
    sigs = cfg["signal"]
    seen_ball, seen_pin, seen_name = {}, {}, set()
    for s in sigs:
        if s["connector"] not in CONNECTORS:
            raise SystemExit(f"{s['name']}: unknown connector {s['connector']}")
        std = s.get("iostandard", default_std)
        if std not in IOSTD:
            raise SystemExit(f"{s['name']}: unsupported IO standard {std}")
        if s["dir"] not in ("in", "out", "inout"):
            raise SystemExit(f"{s['name']}: bad dir {s['dir']}")
        k = (s["connector"], s["pin"])
        for tbl, key, what in ((seen_ball, s["ball"], "ball"), (seen_pin, k, "connector pin")):
            if key in tbl:
                raise SystemExit(f"{s['name']}: {what} {key} already used by {tbl[key]}")
            tbl[key] = s["name"]
        if s["name"] in seen_name:
            raise SystemExit(f"duplicate signal {s['name']}")
        seen_name.add(s["name"])

    lines = [
        "# GENERATED by rtl/vivado/gen_xdc.py from pins.toml. Do not edit by hand.",
        "# Board-fixed pins (Ethernet PHY on EMIO) are in ebaz4205_board.xdc.",
        "",
    ]
    for conn in sorted(CONNECTORS):
        group = [s for s in sigs if s["connector"] == conn]
        if not group:
            continue
        lines.append(f"## {conn}")
        for s in sorted(group, key=lambda s: s["pin"]):
            std = s.get("iostandard", default_std)
            c = "" if s.get("active", False) else "#"
            port = f"{{{s['name']}}}" if "[" in s["name"] else s["name"]
            note = f"  ; # {conn}-{s['pin']} {s['dir']}" + (f", {s['note']}" if s.get("note") else "")
            lines.append(
                f"{c}set_property -dict {{PACKAGE_PIN {s['ball']} IOSTANDARD {std}}} [get_ports {port}]{note}"
            )
            if s.get("pulltype"):
                lines.append(f"{c}set_property PULLTYPE {s['pulltype']} [get_ports {port}]")
        lines.append("")
    return "\n".join(lines) + "\n"


def main(argv):
    cfg = tomllib.loads(SRC.read_text())
    text = render(cfg)
    if "--check" in argv:
        old = OUT.read_text() if OUT.exists() else ""
        if old != text:
            print("ebaz4205.xdc is out of date; run gen_xdc.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
