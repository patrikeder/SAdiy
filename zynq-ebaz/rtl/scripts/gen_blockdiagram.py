#!/usr/bin/env python3
"""Generate docs/blockdiagram.svg: block diagram and connectivity of the whole EBAZ_SAdiy design.

The drawing is hand-laid-out (coordinates below), the facts come from rtl/fpga/ebaz_sadiy_top.sv and
rtl/src/sadiy_top.sv. When ports, EMIO lines or engine modules change, edit this file and regenerate:
    python3 rtl/scripts/gen_blockdiagram.py          # write docs/blockdiagram.svg
    python3 rtl/scripts/gen_blockdiagram.py --check  # exit 1 if the file is out of date
"""
import sys
from pathlib import Path
from xml.sax.saxutils import escape

OUT = Path(__file__).resolve().parents[2] / "docs" / "blockdiagram.svg"

W, H = 1740, 1150
C = dict(ps="#dbe7f7", psl="#2b5c9e", eng="#e1f3e1", engl="#2f7d32", pad="#ececec", padl="#666",
         ext="#fdebd3", extl="#b8651b", dash="#999", txt="#1a1a1a", sub="#555", cross="#8a8a8a")

o = []


def t(x, y, s, size=12, anchor="start", weight="normal", fill=None, italic=False):
    st = ' font-style="italic"' if italic else ""
    o.append(f'<text x="{x}" y="{y}" font-size="{size}" text-anchor="{anchor}" font-weight="{weight}" '
             f'fill="{fill or C["txt"]}"{st}>{escape(s)}</text>')


def box(x, y, w, h, title, lines=(), fill="#fff", stroke="#333", dash=False, size=12, tsize=None, rx=4):
    d = ' stroke-dasharray="6 4"' if dash else ""
    o.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="{fill}" stroke="{stroke}" '
             f'stroke-width="1.4"{d}/>')
    ty = y + 17
    if title:
        t(x + w / 2, ty, title, tsize or size, "middle", "bold")
        ty += 15
    for s in lines:
        t(x + w / 2, ty, s, size - 1.5, "middle", fill=C["sub"])
        ty += 13


def arrow(pts, both=False, color="#222", dash=False, width=1.5, back=False):
    p = " ".join(f"{a},{b}" for a, b in pts)
    d = ' stroke-dasharray="5 3"' if dash else ""
    ms = ' marker-start="url(#ah)"' if (both or back) else ""
    me = "" if back else ' marker-end="url(#ah)"'
    o.append(f'<polyline points="{p}" fill="none" stroke="{color}" stroke-width="{width}"{d}{ms}{me}/>')


def line(pts, color="#222", width=1.5):
    p = " ".join(f"{a},{b}" for a, b in pts)
    o.append(f'<polyline points="{p}" fill="none" stroke="{color}" stroke-width="{width}"/>')


# ------------------------------------------------------------------ frame
o.append(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" '
         f'font-family="DejaVu Sans, Verdana, sans-serif">')
o.append('<defs><marker id="ah" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" '
         'orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="#222"/></marker></defs>')
o.append(f'<rect width="{W}" height="{H}" fill="#fff"/>')
t(30, 30, "SAdiy on EBAZ4205 (XC7Z010): block diagram and connectivity of the whole design", 18, weight="bold")
t(30, 48, "Source: rtl/fpga/ebaz_sadiy_top.sv, rtl/src/sadiy_top.sv. Generated by rtl/scripts/gen_blockdiagram.py. "
          "Pad balls: docs/pinmap.md. Linux EMIO GPIO line = 54 + n.", 11, fill=C["sub"])

# ------------------------------------------------------------------ PS
PSX, PSY, PSW, PSH = 30, 62, 240, 1040
box(PSX, PSY, PSW, PSH, "", fill=C["ps"], stroke=C["psl"], rx=8)
t(PSX + PSW / 2, PSY + 24, "Zynq PS7", 16, "middle", "bold", C["psl"])
for i, s in enumerate(["2x Cortex-A9, Linux, sweepd", "DDR3, MIO[53:0]: not via the PL"]):
    t(PSX + PSW / 2, PSY + 44 + 14 * i, s, 11, "middle", fill=C["sub"])

PX = PSX + PSW  # right edge of the PS, where its ports leave

# (label, y)
UP = [("I2C0 (EMIO)", 150), ("ENET0 MII + MDIO", 205), ("SPI1 (EMIO)", 260), ("EMIO GPIO [9:8]", 315),
      ("EMIO GPIO [12:10]", 370), ("EMIO GPIO [17:13]", 425), ("EMIO GPIO [6]", 480), ("EMIO GPIO [7]", 535)]
for s, y in UP:
    t(PX - 8, y + 4, s, 11.5, "end")

LOW = dict(axi=660, clk=730, irq=775, spi0=1000, gpio=1040)
t(PX - 8, LOW["axi"] + 4, "M_AXI_GP0 (AXI3, 32 b)", 11.5, "end")
t(PX - 8, LOW["clk"] + 4, "FCLK0 100 MHz, ARESETN", 11.5, "end")
t(PX - 8, LOW["irq"] + 4, "IRQ_F2P[0]", 11.5, "end")
t(PX - 8, LOW["spi0"] + 4, "SPI0 (EMIO)", 11.5, "end")
t(PX - 8, LOW["gpio"] + 4, "EMIO GPIO [5:0]", 11.5, "end")

# ------------------------------------------------------------------ PL frame
PLX, PLY, PLW, PLH = 330, 62, 1050, 1040
o.append(f'<rect x="{PLX}" y="{PLY}" width="{PLW}" height="{PLH}" rx="8" fill="none" stroke="{C["dash"]}" '
         f'stroke-width="1.6" stroke-dasharray="9 5"/>')
t(PLX + 12, PLY + 20, "Programmable logic (ebaz_sadiy_top.sv, one clock: FCLK0 100 MHz)", 13, weight="bold", fill="#444")
t(PLX + 12, PLY + 36, "pad cells below: no logic, only IOBUF / OBUFT / direct wires", 11, fill=C["sub"])
PLR = PLX + PLW  # right edge of PL

# ------------------------------------------------------------------ external devices
EXX, EXW = 1450, 270


def ext(y, h, title, lines):
    box(EXX, y, EXW, h, title, lines, fill=C["ext"], stroke=C["extl"], size=12)


ext(128, 44, "ADS1115 (I2C 0x48)", ["main ADC of the detector, read by the PS"])
ext(183, 44, "Ethernet PHY (EBAZ4205)", ["MII on EMIO, 25 MHz PHY clock out (FCLK1)"])
ext(238, 100, "Adapter LCD, Sitronix ST7789", ["SCL R19, SDA P20, CS T20 (SPI1)", "DC R18, RES N17 (GPIO)",
                                             "driven by Linux fbtft"])
ext(352, 36, "Adapter LEDs 1..3", ["H18, K17, E19"])
ext(407, 36, "Adapter keys 1..5", ["T19, P19, U20, U19, V20 (active low)"])
ext(458, 295, "ADF4351 eval board (LO)", ["25 MHz osc, 5 V jack", "CE and LD pins on the header",
                                         "CLK / DAT / LE: 32-bit SPI writes", "RF out -> mixer LO"])
ext(965, 120, "PE4302 module (attenuator)", ["parallel V1..V6 = 0.5 .. 16 dB", "pull-ups: 31.5 dB until driven",
                                              "RF in -> PE4302 -> amp -> AD831 mixer", "-> detector -> ADS1115 (analog)"])

# pad cells (upper) ----------------------------------------------------------------
CX, CW, CH = 700, 230, 34


def padcell(y, text, sub=None):
    box(CX, y - CH / 2, CW, CH, "", fill=C["pad"], stroke=C["padl"], rx=3)
    t(CX + CW / 2, y - 2 if sub else y + 4, text, 11, "middle", "bold")
    if sub:
        t(CX + CW / 2, y + 11, sub, 9.5, "middle", fill=C["sub"])


def lab(x, y, s, anchor="middle"):
    t(x, y, s, 10, anchor, fill=C["sub"])


# 1 I2C
y = 150
arrow([(PX, y), (CX, y)], both=True)
padcell(y, "IOBUF x2", "i2c_scl, i2c_sda")
arrow([(CX + CW, y), (EXX, y)], both=True)
lab(515, y - 6, "SCL / SDA")
# 2 ENET
y = 205
arrow([(PX, y), (CX, y)], both=True)
padcell(y, "direct + IOBUF (MDIO)", "MII 4+4 data, clocks, MDC / MDIO")
arrow([(CX + CW, y), (EXX, y)], both=True)
lab(515, y - 6, "MII, MDC / MDIO")
# 3 SPI1
y = 260
arrow([(PX, y), (CX, y)])
padcell(y, "direct", "lcd_scl, lcd_sda, lcd_cs")
arrow([(CX + CW, y), (EXX, y)])
lab(515, y - 6, "SCLK / MOSI / SS0")
# 4 GPIO 9:8
y = 315
arrow([(PX, y), (CX, y)], both=True)
padcell(y, "IOBUF x2", "lcd_dc (n=8), lcd_res (n=9)")
arrow([(CX + CW, y), (EXX, y)], both=True)
lab(515, y - 6, "DC / RES")
# 5 LEDs
y = 370
arrow([(PX, y), (CX, y)])
padcell(y, "OBUFT x3", "led[0..2] (n=10..12)")
arrow([(CX + CW, y), (EXX, y)])
lab(515, y - 6, "outputs")
# 6 keys
y = 425
arrow([(CX, y), (PX, y)])
padcell(y, "direct inputs x5", "keys[0..4] (n=13..17), pull-up")
arrow([(EXX, y), (CX + CW, y)])
lab(515, y - 6, "raw level")
# 7 CE
y = 480
arrow([(PX, y), (CX, y)], both=True)
padcell(y, "IOBUF", "adf4351_ce (n=6)")
arrow([(CX + CW, y), (EXX, y)], both=True)
lab(515, y - 6, "CE (high = on)")
# 8 LD
y = 535
arrow([(CX, y), (PX, y)])
padcell(y, "input buffer", "adf4351_ld (n=7)")
arrow([(EXX, y), (CX + CW, y)])
lab(515, y - 6, "lock detect")

# ------------------------------------------------------------------ engine sadiy_top
EX, EY, EW, EH = 530, 570, 820, 520
box(EX, EY, EW, EH, "", fill=C["eng"], stroke=C["engl"], rx=6)
t(EX + 10, EY + 18, "sadiy_top (rtl/src): the sweep engine", 13, "start", "bold", C["engl"])

# AXI converter in the BD (left of the engine)
box(345, 625, 150, 70, "AXI protocol", ["converter AXI3 to", "AXI4-Lite (block design)"], fill="#fff", stroke="#666",
    size=11.5)
arrow([(PX, LOW["axi"]), (345, LOW["axi"])], both=True)
arrow([(495, LOW["axi"]), (EX + 22, LOW["axi"])], both=True)
t(345, 618, "AXI4-Lite, 12-bit address", 9.5, "start", fill=C["sub"], italic=True)

# clock / reset tab
arrow([(PX, LOW["clk"]), (EX, LOW["clk"])])
t(445, LOW["clk"] - 6, "clk, resetn", 9.5, "middle", fill=C["sub"], italic=True)
# irq
arrow([(EX, LOW["irq"]), (PX, LOW["irq"])])
t(445, LOW["irq"] - 6, "irq (sweep done)", 9.5, "middle", fill=C["sub"], italic=True)

# column geometry
C1X, C1W = 555, 140     # regs, pin_mux
C2X, C2W = 815, 140     # RAMs, det
C3X, C3W = 1055, 110    # sweep_seq
C4X, C4W = 1225, 80     # spi, mbb

REGY, REGH = 640, 150
box(C1X, REGY, C1W, REGH, "axil_regs", ["generated from", "regmap.toml", "4 KiB at 0x43C0_0000", "CTRL, STATUS, timing,",
                                          "N_ENTRIES, N_AVG,", "SPI_DIV, PE4302, DET_*"],
    fill="#fff", stroke=C["engl"], size=12)

TBY = 640
box(C2X, TBY, C2W, 60, "table RAM", ["2^12 x 44 b", "{W1 flags, W0 SPI word}"], fill="#fff", stroke=C["engl"], size=11.5)
RSY = 720
box(C2X, RSY, C2W, 60, "result RAM", ["2^12 x 32 b", "average sample per point"], fill="#fff", stroke=C["engl"], size=11.5)
DTY = 810
box(C2X, DTY, C2W, 82, "det_sampler", ["sum of N samples from:", "0 PS push (DET_PUSH)", "1 test generator", "2 det_ext port"],
    fill="#fff", stroke=C["engl"], size=11.5)
box(C2X, 902, C2W, 38, "det_ext (tied 0)", ["PL ADC reader (S10)"], fill="#fff", stroke="#888", dash=True, size=11)
arrow([(C2X + C2W / 2, 902), (C2X + C2W / 2, DTY + 82)], color="#888", dash=True)

SQY, SQH = 640, 300
box(C3X, SQY, C3W, SQH, "sweep_seq", ["FSM per entry:", "", "1 set PE4302", "  (make-before-break)", "2 send SPI words",
                                       "3 wait lock", "  (stable time,", "  timeout)", "4 settle", "5 sample, average", "6 write result",
                                       "", "stop_on_err, abort,", "error index"], fill="#fff", stroke=C["engl"], size=12)

box(C4X, 640, C4W, 60, "adf4351_spi", ["32 b MSB first", "SPI_DIV clock"], fill="#fff", stroke=C["engl"], size=11.5, tsize=10)
box(C4X, 730, C4W, 60, "pe4302_mbb", ["glitch-free", "attenuation"], fill="#fff", stroke=C["engl"], size=11.5, tsize=10.5)

# pin_mux across the bottom
PMY, PMH = 975, 100
box(C1X, PMY, EX + EW - 10 - C1X, PMH, "pin_mux", ["CTRL.pin_owner: PS (bench mode, Linux drives the SPI0 / GPIO lines)  or  engine (sweep)",
                                                    "PE4302 outputs are tri-stated until driven; default LE / CLK idle levels set here"],
    fill="#fff", stroke=C["engl"], size=12)

# regs <-> seq control line over the top
arrow([(C1X + 60, REGY), (C1X + 60, EY + 40), (C3X + 30, EY + 40), (C3X + 30, SQY)], both=True)
t(800, EY + 32, "start, abort, soft_reset, n_entries, timing, owner request  /  status, counters, error index, irq",
  10, "middle", fill=C["sub"])
# regs <-> table / result
arrow([(C1X + C1W, TBY + 25), (C2X, TBY + 25)])
t((C1X + C1W + C2X) / 2, TBY + 14, "TABLE_ADDR/W0/W1", 9, "middle", fill=C["sub"])
arrow([(C2X, RSY + 25), (C1X + C1W, RSY + 25)])
t((C1X + C1W + C2X) / 2, RSY + 14, "RESULT_ADDR/DATA", 9, "middle", fill=C["sub"])
# regs -> det
arrow([(C1X + C1W - 25, REGY + REGH), (C1X + C1W - 25, DTY + 40), (C2X, DTY + 40)])
t(C2X - 6, DTY + 28, "DET_CFG / TEST / PUSH", 9, "end", fill=C["sub"])
# seq <-> table / result / det
arrow([(C3X, TBY + 25), (C2X + C2W, TBY + 25)], both=True)
t((C2X + C2W + C3X) / 2, TBY + 14, "raddr / data", 9, "middle", fill=C["sub"])
arrow([(C3X, RSY + 25), (C2X + C2W, RSY + 25)])
t((C2X + C2W + C3X) / 2, RSY + 14, "we, addr, data", 9, "middle", fill=C["sub"])
arrow([(C3X, DTY + 40), (C2X + C2W, DTY + 40)], both=True)
t((C2X + C2W + C3X) / 2, DTY + 28, "run / done,", 9, "middle", fill=C["sub"])
t((C2X + C2W + C3X) / 2, DTY + 38, "sum", 9, "middle", fill=C["sub"])
# seq -> spi, mbb
arrow([(C3X + C3W, 670), (C4X, 670)], both=True)
t((C3X + C3W + C4X) / 2, 662, "start,word", 8.5, "middle", fill=C["sub"])
arrow([(C3X + C3W, 760), (C4X, 760)], both=True)
t((C3X + C3W + C4X) / 2, 752, "load,val", 8.5, "middle", fill=C["sub"])
# spi / mbb -> pin_mux (rails on the right)
R1, R2 = EX + EW - 32, EX + EW - 16
arrow([(C4X + C4W, 670), (R1, 670), (R1, PMY)])
arrow([(C4X + C4W, 760), (R2, 760), (R2, PMY)])
t(R1 - 8, 870, "left rail: adf clk/dat/le", 9, "end", fill=C["sub"])
t(R1 - 8, 883, "right rail: pe_v[5:0]", 9, "end", fill=C["sub"])

# lock detect to the sequencer (from the pad cell, down over the engine top)
LDX = C3X + 85
arrow([(LDX, 535), (LDX, SQY)], color="#222")
o.append(f'<circle cx="{LDX}" cy="535" r="3" fill="#222"/>')
t(LDX + 6, 556, "adf4351_ld to the sequencer", 9.5, "start", fill=C["sub"], italic=True)

# SPI0 / PE GPIO from the PS into pin_mux
arrow([(PX, LOW["spi0"]), (C1X, LOW["spi0"])])
t(440, LOW["spi0"] - 6, "SCLK / MOSI / SS0 = LE (Linux, bench)", 9.5, "middle", fill=C["sub"], italic=True)
arrow([(PX, LOW["gpio"]), (C1X, LOW["gpio"])], both=True)
t(440, LOW["gpio"] - 6, "tri_o / tri_t out, pad level back", 9.5, "middle", fill=C["sub"], italic=True)

# pin_mux outputs to ADF4351 / PE4302
adfx = EX + EW + 12
arrow([(EX + EW - 10, PMY + 25), (adfx, PMY + 25), (adfx, 720), (EXX, 720)], both=False)
t(adfx + 4, 850, "adf4351_clk / dat / le", 9.5, "start", fill=C["sub"], italic=True)
t(adfx + 4, 862, "(3 pads, direct)", 9.5, "start", fill=C["sub"], italic=True)
arrow([(EX + EW - 10, PMY + 75), (EXX, PMY + 75)], both=True)
t(1395, PMY + 69, "IOBUF x6", 9.5, "middle", fill=C["sub"], italic=True)
t(1395, PMY + 84, "pe4302_v[5:0]", 9.5, "middle", fill=C["sub"], italic=True)

# ------------------------------------------------------------------ legend
LY = 1125
for i, (fill, stroke, s) in enumerate([(C["ps"], C["psl"], "processing system"),
                                        (C["eng"], C["engl"], "RTL of the sweep engine"),
                                        (C["pad"], C["padl"], "pad cells (no logic)"),
                                        (C["ext"], C["extl"], "devices outside the FPGA")]):
    x = 30 + 250 * i
    o.append(f'<rect x="{x}" y="{LY - 11}" width="18" height="12" fill="{fill}" stroke="{stroke}"/>')
    t(x + 26, LY, s, 11)
t(1000, LY, "not built yet: det_ext (PL ADC reader), PL access to keys / LEDs", 11, fill=C["sub"])
o.append("</svg>")

text = "\n".join(o) + "\n"
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        print("blockdiagram.svg is out of date")
        sys.exit(1)
    print("blockdiagram.svg is current")
else:
    OUT.write_text(text)
    print(f"wrote {OUT}")
