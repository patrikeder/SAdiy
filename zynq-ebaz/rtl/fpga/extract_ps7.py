#!/usr/bin/env python3
"""Extract the PS7 configuration of the working EBAZ4205 design into ps7_config.tcl.

The PS7 settings (DDR, clocks, MIO, SD0, UART1, ENET0 on EMIO) are copied from the block design
JSON of the EBAZ_extender project, never re-derived. The overrides that make the SAdiy design
(and the Phase 1 design of session L, whose boot image we run on) are listed in OVERRIDES below
and written into the same file as a second dict.

Usage: python3 -I extract_ps7.py [path/to/ebaz4205.bd] [out.tcl]
Defaults: the EBAZ_extender project on the development machine, ps7_config.tcl next to this file.
Read-only / derived parameters (PCW_ACT_*, PCW_UIPARAM_ACT_*, PCW_MIO_TREE_*) are dropped;
Vivado recomputes them. Standard library only.
"""
import json
import sys
from pathlib import Path

DEFAULT_BD = ("/media/patrik/Workspaces/HW/Vivado/EBAZ_extender/EBAZ_extender.srcs/"
              "sources_1/bd/ebaz4205/ebaz4205.bd")
SKIP_PREFIX = ("PCW_ACT_", "PCW_UIPARAM_ACT_", "PCW_MIO_TREE_")

# Must stay identical to the overrides in session L's phase1.tcl (check_ps7.py compares them).
OVERRIDES = [
    ("PCW_FPGA0_PERIPHERAL_FREQMHZ", "100"),
    ("PCW_GPIO_EMIO_GPIO_WIDTH", "16"),
    ("PCW_GPIO_EMIO_GPIO_IO", "16"),
    ("PCW_CAN0_PERIPHERAL_ENABLE", "0"),
    ("PCW_CAN1_PERIPHERAL_ENABLE", "0"),
    ("PCW_UART0_PERIPHERAL_ENABLE", "0"),
]


def main(argv):
    src = Path(argv[0] if argv else DEFAULT_BD)
    out = Path(argv[1]) if len(argv) > 1 else Path(__file__).with_name("ps7_config.tcl")
    ps7 = json.loads(src.read_text())["design"]["components"]["processing_system7_0"]
    params = ps7["parameters"]
    lines = [
        "# GENERATED by extract_ps7.py from the EBAZ_extender block design. Do not edit.",
        f"# Source: {src}",
        f"# Source IP: {ps7['vlnv']}",
        "# ps7_base: user settings copied from the working board design.",
        "# ps7_overrides: SAdiy changes, identical to session L's Phase 1 (FCLK0 100 MHz, 16 EMIO GPIO,",
        "#   CAN0/CAN1/UART0 off). Apply with: set_property -dict $ps7_base $ps; set_property -dict $ps7_overrides $ps",
        "set ps7_base [dict create \\",
    ]
    n = 0
    for k in sorted(params):
        if not k.startswith("PCW_") or k.startswith(SKIP_PREFIX):
            continue
        lines.append(f"  CONFIG.{k} {{{params[k]['value']}}} \\")
        n += 1
    lines.append("]")
    lines.append("set ps7_overrides [dict create \\")
    for k, v in OVERRIDES:
        lines.append(f"  CONFIG.{k} {{{v}}} \\")
    lines.append("]")
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}: {n} base parameters, {len(OVERRIDES)} overrides")


if __name__ == "__main__":
    main(sys.argv[1:])
